import { mkdtempSync, realpathSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { beforeEach, describe, expect, it, vi } from "vitest";
import { codex } from "../src/adapters/codex.js";
import { hookRunnerPath } from "../src/core/hook-runner.js";
import type { Operation } from "../src/core/plan.js";
import { makeRepo, planWith } from "./helpers.js";

const CONFIG = ".codex/config.toml";
const planFor = (files: Record<string, string>) => planWith(codex, files);
const value = (ops: Operation[], key: string) =>
  ops.find((op) => op.kind !== "symlink" && "key" in op && op.key.join(" ") === key);

let codexHome: string;
beforeEach(() => {
  codexHome = realpathSync(mkdtempSync(join(tmpdir(), "agents-setup-codex-")));
  vi.stubEnv("CODEX_HOME", codexHome);
  return () => vi.unstubAllEnvs();
});

describe("codex adapter", () => {
  it("puts all rules into developer_instructions, naming where each applies", () => {
    const { operations } = planFor({
      ".agents/rules/general.md": "- Be clear.\n",
      "frontend/.agents/rules/react.md": '---\npaths: ["src/**/*.tsx"]\n---\n- Hooks.\n',
    });
    expect(value(operations, "developer_instructions")).toEqual({
      kind: "merge-json",
      path: CONFIG,
      key: ["developer_instructions"],
      value:
        "Project rules from .agents/rules/, generated by agents-setup. Follow them.\n\n" +
        "## .agents/rules/general.md\n\n- Be clear.\n\n" +
        "## frontend/.agents/rules/react.md (for files matching frontend/src/**/*.tsx)\n\n- Hooks.\n",
    });
  });

  it("skips rules when the user's own config sets developer_instructions", () => {
    writeFileSync(join(codexHome, "config.toml"), 'developer_instructions = "mine"\n');
    const { operations, warnings } = planFor({ ".agents/rules/general.md": "- Be clear.\n" });
    expect(operations).toEqual([]);
    expect(warnings[0]).toContain("Rules skipped");
  });

  it("turns variable references into names Codex forwards", () => {
    const { operations, warnings, approvals } = planFor({
      ".agents/mcp.yaml": [
        "servers:",
        "  docs: { transport: http, url: https://x.dev/mcp, headers: { Authorization: 'Bearer ${T}', X-Key: '${K}', X-Team: web } }",
        "  db: { transport: stdio, command: npx, args: [db-mcp], env: { DB_URL: '${DB_URL}', MODE: ro } }",
        "  bad: { transport: stdio, command: npx, args: [x, '${TOKEN}'] }",
      ].join("\n"),
      "frontend/.agents/mcp.yaml":
        "servers:\n  ui: { transport: stdio, command: npx, env: { KEY: '${OTHER}' } }\n",
    });
    expect(value(operations, "mcp_servers docs")).toMatchObject({
      value: {
        url: "https://x.dev/mcp",
        bearer_token_env_var: "T",
        env_http_headers: { "X-Key": "K" },
        http_headers: { "X-Team": "web" },
      },
      approval: "mcp:.:docs",
    });
    expect(value(operations, "mcp_servers db")).toMatchObject({
      value: { command: "npx", args: ["db-mcp"], env: { MODE: "ro" }, env_vars: ["DB_URL"] },
    });
    expect(value(operations, "mcp_servers bad")).toBeUndefined();
    expect(value(operations, "mcp_servers ui")).toBeUndefined();
    expect(approvals.map((a) => a.id)).toEqual(["mcp:.:docs", "mcp:.:db"]);
    expect(warnings).toEqual(
      expect.arrayContaining([
        'MCP server "bad" skipped for Codex: its command or args use a variable',
        expect.stringContaining('"ui" skipped for Codex: env KEY must be plain text or ${KEY}'),
      ]),
    );
  });

  it("writes hooks that call the Codex runner and asks for a review", () => {
    const { operations, warnings } = planFor({
      "backend/.agents/hooks.yaml":
        'hooks:\n  fmt:\n    event: after-edit\n    match: "**/*.py"\n    command: ruff format {file}\n',
    });
    const fmt = value(operations, "hooks PostToolUse");
    expect(fmt).toMatchObject({ kind: "merge-json-item", id: "backend:fmt" });
    const entry = fmt?.kind === "merge-json-item" ? (fmt.value as Record<string, unknown>) : {};
    expect(entry.matcher).toBe("apply_patch|Edit|Write");
    expect(JSON.stringify(entry.hooks)).toContain(`git -C \\".\\" rev-parse`);
    expect(JSON.stringify(entry.hooks)).toContain(hookRunnerPath("codex"));
    expect(operations.filter((op) => op.path === hookRunnerPath("codex"))).toHaveLength(1);
    expect(warnings).toContain(
      "Codex runs a new or changed hook only after you review it with /hooks",
    );
  });

  it("enables plugins and adds their marketplaces", () => {
    const { operations, warnings, approvals } = planFor({
      ".agents/plugins.yaml":
        "plugins:\n  codex:\n    - name: tool\n      marketplace: acme\n      source: acme/codex-plugins\n    - name: lost\n      marketplace: other\n    - name: nowhere\n",
    });
    expect(value(operations, "plugins tool@acme")).toMatchObject({ value: { enabled: true } });
    expect(value(operations, "marketplaces acme")).toMatchObject({
      value: { source_type: "git", source: "https://github.com/acme/codex-plugins.git" },
    });
    expect(value(operations, "plugins lost@other")).toBeDefined();
    expect(approvals.map((a) => a.id)).toEqual(["plugin:.:tool", "plugin:.:lost"]);
    expect(warnings).toEqual(
      expect.arrayContaining([
        expect.stringContaining('add the "other" marketplace'),
        expect.stringContaining('"nowhere" (.) has no marketplace'),
      ]),
    );
  });

  it("warns until the project is trusted, and about AGENTS.override.md", () => {
    const files = { ".agents/rules/a.md": "- A.\n", "AGENTS.override.md": "x\n" };
    const untrusted = planFor(files);
    expect(untrusted.warnings).toEqual([
      "AGENTS.override.md exists, so Codex reads it instead of AGENTS.md there",
      `Codex reads ${CONFIG} only in trusted projects: trust this folder when Codex asks`,
    ]);

    const root = makeRepo({});
    writeFileSync(
      join(codexHome, "config.toml"),
      `[projects."${root}"]\ntrust_level = "trusted"\n`,
    );
    const trusted = planWith(codex, files, root);
    expect(trusted.operations).toHaveLength(1);
    expect(trusted.warnings).toEqual([
      "AGENTS.override.md exists, so Codex reads it instead of AGENTS.md there",
    ]);
  });
});
