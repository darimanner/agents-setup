import { describe, expect, it } from "vitest";
import { claudeCode } from "../src/adapters/claude-code.js";
import { HOOK_RUNNER_PATH } from "../src/core/hook-runner.js";
import type { Operation } from "../src/core/plan.js";
import { planWith } from "./helpers.js";

const planFor = (files: Record<string, string>) => planWith(claudeCode, files);

const find = (ops: Operation[], path: string) => ops.filter((op) => op.path === path);
const SKILL = (name: string) => `---\nname: ${name}\ndescription: x\n---\n`;

describe("claude code adapter", () => {
  it("copies rules read-only, prefixing nested paths", () => {
    const { operations } = planFor({
      ".agents/rules/general.md": "- Be clear.\n",
      "frontend/web/.agents/rules/react.md": '---\npaths: ["src/**/*.tsx"]\n---\n- Hooks.\n',
      "frontend/web/.agents/rules/css.md": "- Tokens.\n",
    });
    const general = find(operations, ".claude/rules/agents-setup/general.md")[0];
    expect(general).toMatchObject({ kind: "write", readonly: true });
    expect(general?.kind === "write" && general.content).toBe(
      "<!-- Generated by agents-setup from .agents/rules/general.md. Edit that file, not this copy. -->\n- Be clear.\n",
    );
    const react = find(operations, ".claude/rules/agents-setup/frontend__web__react.md")[0];
    expect(react?.kind === "write" && react.content).toContain(
      '---\npaths:\n  - "frontend/web/src/**/*.tsx"\n---\n',
    );
    const css = find(operations, ".claude/rules/agents-setup/frontend__web__css.md")[0];
    expect(css?.kind === "write" && css.content).toContain('  - "frontend/web/**"\n');
  });

  it("links skills next to their layer", () => {
    const { operations } = planFor({
      ".agents/skills/review/SKILL.md": SKILL("review"),
      "frontend/.agents/skills/ui/SKILL.md": SKILL("ui"),
    });
    expect(find(operations, ".claude/skills/review")).toEqual([
      { kind: "symlink", path: ".claude/skills/review", target: "../../.agents/skills/review" },
    ]);
    expect(find(operations, "frontend/.claude/skills/ui")).toEqual([
      { kind: "symlink", path: "frontend/.claude/skills/ui", target: "../../.agents/skills/ui" },
    ]);
  });

  it("writes MCP servers with types, enables them and warns for nested layers", () => {
    const { operations, warnings } = planFor({
      ".agents/mcp.yaml":
        "servers:\n  docs: { transport: http, url: https://x.dev/mcp, headers: { A: '${T}' } }\n",
      "frontend/.agents/mcp.yaml":
        "servers:\n  ui: { transport: stdio, command: npx, args: [shadcn, mcp] }\n",
    });
    const mcp = find(operations, ".mcp.json");
    expect(mcp).toEqual([
      {
        kind: "merge-json",
        path: ".mcp.json",
        key: ["mcpServers", "docs"],
        value: { type: "http", url: "https://x.dev/mcp", headers: { A: "${T}" } },
        approval: "mcp:.:docs",
      },
      {
        kind: "merge-json",
        path: ".mcp.json",
        key: ["mcpServers", "ui"],
        value: { type: "stdio", command: "npx", args: ["shadcn", "mcp"] },
        approval: "mcp:frontend:ui",
      },
    ]);
    const enabled = find(operations, ".claude/settings.local.json");
    expect(
      enabled.map((op) => op.kind === "merge-json-item" && [op.key, op.id, op.approval]),
    ).toEqual([
      [["enabledMcpjsonServers"], "docs", "mcp:.:docs"],
      [["enabledMcpjsonServers"], "ui", "mcp:frontend:ui"],
    ]);
    expect(warnings).toEqual([
      expect.stringContaining('"ui" from frontend is active for the whole project'),
    ]);
  });

  it("plans an identical server from two layers once", () => {
    const server = "servers:\n  docs: { transport: http, url: https://x.dev/mcp }\n";
    const { operations, approvals } = planFor({
      ".agents/mcp.yaml": server,
      "a/.agents/mcp.yaml": server,
    });
    expect(find(operations, ".mcp.json")).toHaveLength(1);
    expect(approvals.map((a) => a.id)).toEqual(["mcp:.:docs"]);
  });

  it("maps hook events and installs the runner", () => {
    const { operations } = planFor({
      "backend/.agents/hooks.yaml":
        'hooks:\n  fmt:\n    event: after-edit\n    match: "**/*.py"\n    command: ruff format {file}\n  guard:\n    event: before-tool\n    match: Bash\n    command: ./guard.sh\n',
    });
    const hooks = operations.filter((op) => op.kind === "merge-json-item");
    expect(
      hooks.map((op) => op.kind === "merge-json-item" && [op.key, op.id, op.approval]),
    ).toEqual([
      [["hooks", "PostToolUse"], "backend:fmt", "hook:backend:fmt"],
      [["hooks", "PreToolUse"], "backend:guard", "hook:backend:guard"],
    ]);
    const fmt =
      hooks[0]?.kind === "merge-json-item" ? (hooks[0].value as Record<string, unknown>) : {};
    expect(fmt.matcher).toBe("Write|Edit|MultiEdit");
    expect(JSON.stringify(fmt.hooks)).toContain(HOOK_RUNNER_PATH);
    expect(JSON.stringify(fmt.hooks)).toContain("ruff format {file}");
    const guard =
      hooks[1]?.kind === "merge-json-item" ? (hooks[1].value as Record<string, unknown>) : {};
    expect(guard.matcher).toBe("Bash");
    expect(find(operations, HOOK_RUNNER_PATH)).toHaveLength(1);
  });

  it("enables plugins and adds marketplaces with a source", () => {
    const { operations, warnings } = planFor({
      ".agents/plugins.yaml":
        "plugins:\n  claude-code:\n    - name: superpowers\n      marketplace: claude-plugins-official\n    - name: tool\n      marketplace: acme\n      source: acme/claude-plugins\n    - name: lost\n      marketplace: other\n  opencode:\n    - name: x\n",
    });
    const keys = operations.map((op) => op.kind === "merge-json" && op.key.join(" "));
    expect(keys).toEqual([
      "enabledPlugins superpowers@claude-plugins-official",
      "enabledPlugins tool@acme",
      "extraKnownMarketplaces acme",
      "enabledPlugins lost@other",
    ]);
    expect(operations[2]).toMatchObject({
      value: { source: { source: "github", repo: "acme/claude-plugins" } },
      approval: "plugin:.:tool",
    });
    expect(warnings).toEqual([expect.stringContaining('"other" marketplace')]);
  });

  it("warns when a CLAUDE.md would hide AGENTS.md", () => {
    const { warnings } = planFor({ "AGENTS.md": "x", "CLAUDE.md": "y" });
    expect(warnings).toEqual([expect.stringContaining("CLAUDE.md exists")]);
  });

  it("gives every operation that needs approval a known approval id", () => {
    const plan = planFor({
      ".agents/mcp.yaml": "servers:\n  docs: { transport: http, url: https://x.dev/mcp }\n",
      ".agents/hooks.yaml": "hooks:\n  s: { event: stop, command: echo }\n",
    });
    const ids = new Set(plan.approvals.map((a) => a.id));
    for (const op of plan.operations) {
      if (op.approval !== undefined) expect(ids.has(op.approval)).toBe(true);
    }
    expect(ids).toEqual(new Set(["mcp:.:docs", "hook:.:s"]));
  });
});
