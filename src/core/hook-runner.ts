/** Where adapters install the runner; agent-neutral so every adapter can share it. */
export const HOOK_RUNNER_PATH = ".agents/.state/bin/hook.mjs";

export interface HookSpec {
  event: string;
  layer: string;
  match?: string;
  command: string;
}

/**
 * Source of the runner every generated hook calls. It finds the repo root from its own
 * location, filters after-edit events to files inside the hook's layer that match its glob,
 * substitutes {file}, and runs the command with the agent's stdin and exit code passed through.
 */
export const HOOK_RUNNER = String.raw`#!/usr/bin/env node
// Generated by agents-setup. Runs one hook from a layer's hooks.yaml; do not edit.
import { spawnSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { dirname, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const spec = JSON.parse(process.argv[2] ?? "{}");

function globToRegExp(glob) {
  let out = "";
  for (let i = 0; i < glob.length; i++) {
    const c = glob[i];
    if (c === "*" && glob[i + 1] === "*") {
      if (glob[i + 2] === "/") {
        out += "(?:.*/)?";
        i += 2;
      } else {
        out += ".*";
        i += 1;
      }
    } else if (c === "*") out += "[^/]*";
    else if (c === "?") out += "[^/]";
    else if (c === "{") out += "(?:";
    else if (c === "}") out += ")";
    else if (c === ",") out += "|";
    else out += c.replace(/[.+^$()|[\]\\]/g, "\\$&");
  }
  return new RegExp("^" + out + "$");
}

let input = "";
try {
  input = readFileSync(0, "utf8");
} catch {}

let file;
if (spec.event === "after-edit") {
  let data;
  try {
    data = JSON.parse(input);
  } catch {
    process.exit(0);
  }
  const path = data && data.tool_input && data.tool_input.file_path;
  if (typeof path !== "string") process.exit(0);
  const rel = relative(root, resolve(root, path)).split(sep).join("/");
  const base = spec.layer === "." ? "" : spec.layer + "/";
  if (rel.startsWith("../") || !rel.startsWith(base)) process.exit(0);
  if (spec.match && !globToRegExp(spec.match).test(rel.slice(base.length))) process.exit(0);
  file = rel;
}

const quote = (s) => "'" + s.replaceAll("'", "'\\''") + "'";
const command = file === undefined ? spec.command : spec.command.replaceAll("{file}", quote(file));
const result = spawnSync("/bin/sh", ["-c", command], {
  cwd: root,
  input,
  stdio: ["pipe", "inherit", "inherit"],
});
process.exit(result.status ?? 1);
`;

function shellQuote(s: string): string {
  return `'${s.replaceAll("'", `'\\''`)}'`;
}

/**
 * The command an agent's hook config runs. It locates the repo root with git (agents may
 * start in a subfolder) and exits 0 when the runner is missing, so an old checkout never
 * blocks every tool call.
 */
export function runnerCommand(projectDirVar: string, spec: HookSpec): string {
  return `r=$(git -C "${projectDirVar}" rev-parse --show-toplevel 2>/dev/null) && f="$r/${HOOK_RUNNER_PATH}" && [ -f "$f" ] && exec node "$f" ${shellQuote(JSON.stringify(spec))}; exit 0`;
}
