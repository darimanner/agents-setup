import type { AgentId, Hook } from "./types.js";

/** One copy per agent, so uninstalling one agent never removes another agent's runner. */
export const hookRunnerPath = (agent: AgentId) => `.agents/.state/bin/hook-${agent}.mjs`;

export interface HookSpec {
  event: string;
  layer: string;
  match?: string;
  command: string;
}

/**
 * Source of the runner every generated hook calls. It finds the repo root from its own
 * location, filters after-edit events to files inside the hook's layer that match its glob,
 * substitutes {file}, and runs the command with the agent's stdin and exit code passed through.
 * Edited files come from `tool_input.file_path` (Claude Code) or the patch text in
 * `tool_input.command` (Codex `apply_patch`), which may touch several files.
 */
export const HOOK_RUNNER = String.raw`#!/usr/bin/env node
// Generated by agents-setup. Runs one hook from a layer's hooks.yaml; do not edit.
import { spawnSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { dirname, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const spec = JSON.parse(process.argv[2] ?? "{}");

function globToRegExp(glob) {
  let out = "";
  for (let i = 0; i < glob.length; i++) {
    const c = glob[i];
    if (c === "*" && glob[i + 1] === "*") {
      if (glob[i + 2] === "/") {
        out += "(?:.*/)?";
        i += 2;
      } else {
        out += ".*";
        i += 1;
      }
    } else if (c === "*") out += "[^/]*";
    else if (c === "?") out += "[^/]";
    else if (c === "{") out += "(?:";
    else if (c === "}") out += ")";
    else if (c === ",") out += "|";
    else out += c.replace(/[.+^$()|[\]\\]/g, "\\$&");
  }
  return new RegExp("^" + out + "$");
}

let input = "";
try {
  input = readFileSync(0, "utf8");
} catch {}

const run = (command) =>
  spawnSync("/bin/sh", ["-c", command], { cwd: root, input, stdio: ["pipe", "inherit", "inherit"] })
    .status ?? 1;

if (spec.event !== "after-edit") process.exit(run(spec.command));

let data;
try {
  data = JSON.parse(input);
} catch {
  process.exit(0);
}
const tool = (data && data.tool_input) || {};
let paths = [];
if (typeof tool.file_path === "string") paths = [tool.file_path];
else if (typeof tool.command === "string") {
  paths = [...tool.command.matchAll(/^\*\*\* (?:Add File|Update File|Move to): (.+)$/gm)].map(
    (m) => m[1].trim(),
  );
}
const cwd = data && typeof data.cwd === "string" ? data.cwd : root;
const base = spec.layer === "." ? "" : spec.layer + "/";
const files = new Set();
for (const path of paths) {
  const rel = relative(root, resolve(cwd, path)).split(sep).join("/");
  if (rel.startsWith("../") || !rel.startsWith(base)) continue;
  if (spec.match && !globToRegExp(spec.match).test(rel.slice(base.length))) continue;
  files.add(rel);
}

const quote = (s) => "'" + s.replaceAll("'", "'\\''") + "'";
let status = 0;
for (const file of files) {
  const code = run(spec.command.replaceAll("{file}", quote(file)));
  if (status === 0) status = code;
}
process.exit(status);
`;

function shellQuote(s: string): string {
  return `'${s.replaceAll("'", `'\\''`)}'`;
}

/**
 * The command an agent's hook config runs. It locates the repo root with git (agents may
 * start in a subfolder) and exits 0 when the runner is missing, so an old checkout never
 * blocks every tool call. `projectDir` is the agent's launch folder, as a shell expression.
 */
export function runnerCommand(agent: AgentId, projectDir: string, spec: HookSpec): string {
  return `r=$(git -C "${projectDir}" rev-parse --show-toplevel 2>/dev/null) && f="$r/${hookRunnerPath(agent)}" && [ -f "$f" ] && exec node "$f" ${shellQuote(JSON.stringify(spec))}; exit 0`;
}

/**
 * One `{matcher, hooks: [command]}` entry, the shape Claude Code and Codex share. `editTools`
 * matches the agent's file-editing tools; a before-tool hook's `match` is the tool matcher.
 */
export function hookEntry(
  agent: AgentId,
  projectDir: string,
  editTools: string,
  hook: Hook,
): Record<string, unknown> {
  const command = runnerCommand(agent, projectDir, {
    event: hook.event,
    layer: hook.layer,
    ...(hook.match !== undefined && { match: hook.match }),
    command: hook.command,
  });
  const matcher =
    hook.event === "after-edit" ? editTools : hook.event === "before-tool" ? hook.match : undefined;
  return {
    ...(matcher !== undefined && { matcher }),
    hooks: [{ type: "command", command, timeout: 60 }],
  };
}
