import { execFileSync } from "node:child_process";
import { shellQuote } from "./hook-runner.js";
import type { Operation } from "./plan.js";
import type { AgentId } from "./types.js";

export const autosyncPath = (agent: AgentId) => `.agents/.state/bin/autosync-${agent}.sh`;
export const stampPath = (agent: AgentId) => `.agents/.state/stamp-${agent}`;
export const AUTOSYNC_ID = "agents-setup:auto-sync";

/**
 * Prints a digest of every AGENTS.md and `.agents/` file in the work tree, uncommitted edits
 * included. Only git and sh: the session-start check must not need Node when nothing changed.
 * It covers all layers, not just the selected ones, so a layer added by `git pull` is noticed.
 */
const STAMP = String.raw`stamp() {
  files=$(git -c core.quotePath=false ls-files -co --exclude-standard -- ':(glob)**/AGENTS.md' ':(glob)**/.agents/**' ':(exclude).agents/.state/**' | while IFS= read -r f; do [ -f "$f" ] && printf '%s\n' "$f"; done)
  { printf '%s\n' "$files"; [ -n "$files" ] && printf '%s\n' "$files" | git hash-object --stdin-paths; } | git hash-object --stdin
}`;

export function computeStamp(root: string): string {
  return execFileSync("/bin/sh", ["-c", `${STAMP}\nstamp`], { cwd: root, encoding: "utf8" }).trim();
}

/** Runs `sync` for one agent when the stamp changed; otherwise exits at once. */
export function autosyncScript(agent: AgentId, cli: string): string {
  const q = shellQuote(cli);
  return `#!/bin/sh
# Generated by agents-setup: syncs ${agent} at session start when the layers changed. Do not edit.
cd "$(dirname "$0")/../../.." || exit 0
${STAMP}
[ "$(stamp)" = "$(cat ${stampPath(agent)} 2>/dev/null)" ] && exit 0
if [ -f ${q} ]; then
  node ${q} sync --agent ${agent} --quiet
else
  echo "agents-setup: the agent setup of this repo changed; run agents-setup sync"
fi
exit 0
`;
}

/** The session-start hook command; exits 0 whatever happens, so it never blocks a session. */
export function autosyncCommand(agent: AgentId, projectDir: string): string {
  return `r=$(git -C "${projectDir}" rev-parse --show-toplevel 2>/dev/null) && f="$r/${autosyncPath(agent)}" && [ -f "$f" ] && sh "$f"; exit 0`;
}

/** The check script and the current stamp, for adapters that register the hook. */
export function autosyncFiles(agent: AgentId, root: string, cli: string): Operation[] {
  return [
    {
      kind: "write",
      path: autosyncPath(agent),
      content: autosyncScript(agent, cli),
      readonly: true,
    },
    { kind: "write", path: stampPath(agent), content: `${computeStamp(root)}\n`, readonly: true },
  ];
}

/** A `{hooks: [command]}` entry, the SessionStart shape Claude Code and Codex share. */
export function autosyncEntry(agent: AgentId, projectDir: string): Record<string, unknown> {
  return { hooks: [{ type: "command", command: autosyncCommand(agent, projectDir), timeout: 60 }] };
}
