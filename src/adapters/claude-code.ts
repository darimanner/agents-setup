import { existsSync } from "node:fs";
import { join } from "node:path";
import { AUTOSYNC_ID, autosyncEntry, autosyncFiles } from "../core/autosync.js";
import { approvalId } from "../core/fingerprint.js";
import { HOOK_RUNNER, hookEntry, hookRunnerPath } from "../core/hook-runner.js";
import { layerPrefix, rootPaths } from "../core/load.js";
import { type Operation, usedApprovals } from "../core/plan.js";
import { isLinkedWorktree } from "../core/repo.js";
import type { HookEvent, McpServer, PluginRef, Rule } from "../core/types.js";
import type { Adapter, AdapterContext } from "./types.js";

const SETTINGS = ".claude/settings.local.json";
const RULES_DIR = ".claude/rules/agents-setup";
const EDIT_TOOLS = "Write|Edit|MultiEdit";
const OFFICIAL_MARKETPLACE = "claude-plugins-official";
const SHADOWING = ["CLAUDE.md", ".claude/CLAUDE.md", "CLAUDE.local.md"];

const EVENTS: Record<HookEvent, string> = {
  "session-start": "SessionStart",
  "before-tool": "PreToolUse",
  "after-edit": "PostToolUse",
  stop: "Stop",
};

function rulePath(rule: Rule): string {
  const prefix = rule.layer === "." ? "" : `${rule.layer.replaceAll("/", "__")}__`;
  return `${RULES_DIR}/${prefix}${rule.name}.md`;
}

/** Claude Code reads `paths` relative to the repo root, so nested layers get their prefix. */
function ruleContent(rule: Rule): string {
  const paths = rootPaths(rule);
  const frontmatter = paths
    ? `---\npaths:\n${paths.map((p) => `  - ${JSON.stringify(p)}`).join("\n")}\n---\n`
    : "";
  const note = `<!-- Generated by agents-setup from ${rule.file}. Edit that file, not this copy. -->\n`;
  return `${frontmatter}${note}${rule.body}`;
}

function serverConfig(server: McpServer): Record<string, unknown> {
  if (server.transport === "http") {
    return { type: "http", url: server.url, ...(server.headers && { headers: server.headers }) };
  }
  return {
    type: "stdio",
    command: server.command,
    ...(server.args && { args: server.args }),
    ...(server.env && { env: server.env }),
  };
}

function marketplaceSource(source: string): Record<string, string> | undefined {
  if (/^[\w.-]+\/[\w.-]+$/.test(source)) return { source: "github", repo: source };
  if (/^(https?:\/\/|git@)/.test(source)) return { source: "git", url: source };
  return undefined;
}

function pluginOps(plugin: PluginRef, approval: string, warnings: string[]): Operation[] {
  if (!plugin.marketplace) {
    warnings.push(
      `Plugin "${plugin.name}" (${plugin.layer}) has no marketplace; Claude Code needs one, skipped`,
    );
    return [];
  }
  const ops: Operation[] = [
    {
      kind: "merge-json",
      path: SETTINGS,
      key: ["enabledPlugins", `${plugin.name}@${plugin.marketplace}`],
      value: true,
      approval,
    },
  ];
  if (plugin.source) {
    const source = marketplaceSource(plugin.source);
    if (source) {
      ops.push({
        kind: "merge-json",
        path: SETTINGS,
        key: ["extraKnownMarketplaces", plugin.marketplace],
        value: { source },
        approval,
      });
    } else {
      warnings.push(
        `Plugin "${plugin.name}": source "${plugin.source}" is neither owner/repo nor a git URL; marketplace not added`,
      );
    }
  } else if (plugin.marketplace !== OFFICIAL_MARKETPLACE) {
    warnings.push(
      `Plugin "${plugin.name}": add the "${plugin.marketplace}" marketplace yourself or give it a source`,
    );
  }
  return ops;
}

function plan(ctx: AdapterContext) {
  const operations: Operation[] = [];
  const warnings: string[] = [];
  const servers = new Set<string>();

  for (const layer of ctx.contents.map((c) => c.meta.path)) {
    for (const file of SHADOWING) {
      const path = `${layerPrefix(layer)}${file}`;
      if (existsSync(join(ctx.root, path))) {
        warnings.push(`${path} exists, so Claude Code reads it instead of AGENTS.md there`);
      }
    }
  }
  if (isLinkedWorktree(ctx.root)) {
    warnings.push(
      "This is a linked git worktree: Claude Code may read .claude/settings.local.json from the main checkout, so hooks, enabled MCP servers and plugins can be inactive here",
    );
  }

  for (const content of ctx.contents) {
    for (const rule of content.rules) {
      operations.push({
        kind: "write",
        path: rulePath(rule),
        content: ruleContent(rule),
        readonly: true,
      });
    }
    for (const skill of content.skills) {
      operations.push({
        kind: "symlink",
        path: `${layerPrefix(skill.layer)}.claude/skills/${skill.name}`,
        target: `../../.agents/skills/${skill.name}`,
      });
    }
    for (const server of content.mcp) {
      // validate allows the same server in two layers only when identical: plan it once.
      if (servers.has(server.name)) continue;
      servers.add(server.name);
      const approval = approvalId("mcp", server.layer, server.name);
      operations.push(
        {
          kind: "merge-json",
          path: ".mcp.json",
          key: ["mcpServers", server.name],
          value: serverConfig(server),
          approval,
        },
        {
          kind: "merge-json-item",
          path: SETTINGS,
          key: ["enabledMcpjsonServers"],
          id: server.name,
          value: server.name,
          approval,
        },
      );
      if (server.layer !== ".") {
        warnings.push(
          `MCP server "${server.name}" from ${server.layer} is active for the whole project: Claude Code has no per-folder MCP servers`,
        );
      }
    }
    for (const hook of content.hooks) {
      operations.push({
        kind: "merge-json-item",
        path: SETTINGS,
        key: ["hooks", EVENTS[hook.event]],
        id: `${hook.layer}:${hook.name}`,
        value: hookEntry("claude-code", "$CLAUDE_PROJECT_DIR", EDIT_TOOLS, hook),
        approval: approvalId("hook", hook.layer, hook.name),
      });
    }
    for (const plugin of content.plugins) {
      if (plugin.agent !== "claude-code") continue;
      operations.push(
        ...pluginOps(plugin, approvalId("plugin", plugin.layer, plugin.name), warnings),
      );
    }
  }

  if (ctx.autoSync) {
    operations.push(...autosyncFiles("claude-code", ctx.root, ctx.autoSync.cli), {
      kind: "merge-json-item",
      path: SETTINGS,
      key: ["hooks", "SessionStart"],
      id: AUTOSYNC_ID,
      value: autosyncEntry("claude-code", "$CLAUDE_PROJECT_DIR"),
    });
  }
  if (ctx.contents.some((c) => c.hooks.length > 0)) {
    operations.push({
      kind: "write",
      path: hookRunnerPath("claude-code"),
      content: HOOK_RUNNER,
      readonly: true,
    });
  }

  return {
    agent: "claude-code" as const,
    scopes: ctx.scopes,
    operations,
    approvals: usedApprovals(ctx.approvals, operations),
    warnings,
  };
}

export const claudeCode: Adapter = { id: "claude-code", name: "Claude Code", plan };
