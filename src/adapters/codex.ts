const CONFIG = ".codex/config.toml";
// Codex reports file edits as apply_patch; Edit and Write are its aliases.
const EDIT_TOOLS = "apply_patch|Edit|Write";

const EVENTS: Record<HookEvent, string> = {
  "session-start": "SessionStart",
  "before-tool": "PreToolUse",
  "after-edit": "PostToolUse",
  stop: "Stop",
};

const exactRef = (value: string) => /^\$\{([A-Za-z_][A-Za-z0-9_]*)\}$/.exec(value)?.[1];
const hasRef = (value: string) => value.includes("${");

/**
 * Codex expands no `${VAR}`, so references become the names of variables it forwards. Returns
 * why the server cannot be expressed when a reference sits anywhere else.
 */
function serverConfig(server: McpServer): Record<string, unknown> | string {
  if (server.transport === "http") {
    const url = server.url ?? "";
    if (hasRef(url)) return "its url uses a variable";
    const config: Record<string, unknown> = { url };
    const literal: Record<string, string> = {};
    const fromEnv: Record<string, string> = {};
    for (const [name, value] of Object.entries(server.headers ?? {})) {
      const bearer = /^Bearer \$\{([A-Za-z_][A-Za-z0-9_]*)\}$/.exec(value)?.[1];
      const ref = exactRef(value);
      if (bearer && name.toLowerCase() === "authorization") config.bearer_token_env_var = bearer;
      else if (ref) fromEnv[name] = ref;
      else if (!hasRef(value)) literal[name] = value;
      else return `header ${name} mixes text with a variable`;
    }
    if (Object.keys(literal).length > 0) config.http_headers = literal;
    if (Object.keys(fromEnv).length > 0) config.env_http_headers = fromEnv;
    return config;
  }
  const command = server.command ?? "";
  const args = server.args ?? [];
  if (hasRef(command) || args.some(hasRef)) return "its command or args use a variable";
  const env: Record<string, string> = {};
  const envVars: string[] = [];
  for (const [name, value] of Object.entries(server.env ?? {})) {
    if (exactRef(value) === name) envVars.push(name);
    else if (!hasRef(value)) env[name] = value;
    else return `env ${name} must be plain text or \${${name}}: Codex forwards variables by name`;
  }
  return {
    command,
    ...(args.length > 0 && { args }),
    ...(Object.keys(env).length > 0 && { env }),
    ...(envVars.length > 0 && { env_vars: envVars }),
  };
}

/** All rules in one text: Codex has no rules folder, but reads `developer_instructions`. */
function instructions(rules: Rule[]): string {
  const parts = rules.map((rule) => {
    const paths = rootPaths(rule);
    const scope = paths ? ` (for files matching ${paths.join(", ")})` : "";
    return `## ${rule.file}${scope}\n\n${rule.body.trim()}`;
  });
  return `${["Project rules from .agents/rules/, generated by agents-setup. Follow them.", ...parts].join("\n\n")}\n`;
}

function gitSource(source: string): string | undefined {
  if (/^[\w.-]+\/[\w.-]+$/.test(source)) return `https://github.com/${source}.git`;
  if (/^(https?:\/\/|git@)/.test(source)) return source;
  return undefined;
}

function pluginOps(plugin: PluginRef, approval: string, warnings: string[]): Operation[] {
  if (!plugin.marketplace) {
    warnings.push(
      `Plugin "${plugin.name}" (${plugin.layer}) has no marketplace; Codex needs one, skipped`,
    );
    return [];
  }
  const ops: Operation[] = [
    {
      kind: "merge-json",
      path: CONFIG,
      key: ["plugins", `${plugin.name}@${plugin.marketplace}`],
      value: { enabled: true },
      approval,
    },
  ];
  const source = plugin.source && gitSource(plugin.source);
  if (source) {
    ops.push({
      kind: "merge-json",
      path: CONFIG,
      key: ["marketplaces", plugin.marketplace],
      value: { source_type: "git", source },
      approval,
    });
  } else {
    warnings.push(
      `Plugin "${plugin.name}": add the "${plugin.marketplace}" marketplace in Codex yourself or give it an owner/repo or git URL source`,
    );
  }
  return ops;
}

/** The user's own Codex config; read only, never written. */
function userConfig(): Record<string, unknown> {
  const home = process.env.CODEX_HOME ?? join(homedir(), ".codex");
  try {
    return parseToml(readFileSync(join(home, "config.toml"), "utf8"));
  } catch {
    return {};
  }
}

function isTrusted(config: Record<string, unknown>, root: string): boolean {
  const project = isRecord(config.projects) ? config.projects[root] : undefined;
  return isRecord(project) && project.trust_level === "trusted";
}

function plan(ctx: AdapterContext) {
  const operations: Operation[] = [];
  const warnings: string[] = [];
  const servers = new Set<string>();
  const user = userConfig();
  let hooks = 0;

  for (const layer of ctx.contents.map((c) => c.meta.path)) {
    const override = `${layerPrefix(layer)}AGENTS.override.md`;
    if (existsSync(join(ctx.root, override))) {
      warnings.push(`${override} exists, so Codex reads it instead of AGENTS.md there`);
    }
  }

  const rules = ctx.contents.flatMap((c) => c.rules);
  if (rules.length > 0 && user.developer_instructions !== undefined) {
    warnings.push(
      "Rules skipped: your Codex config sets developer_instructions, which a project value would hide",
    );
  } else if (rules.length > 0) {
    operations.push({
      kind: "merge-json",
      path: CONFIG,
      key: ["developer_instructions"],
      value: instructions(rules),
    });
  }

  for (const content of ctx.contents) {
    const layer = content.meta.path;
    if (layer !== "." && content.skills.length > 0) {
      warnings.push(
        `Skills in ${layer}/.agents/skills load only when Codex starts in ${layer} or below`,
      );
    }
    for (const server of content.mcp) {
      // validate allows the same server in two layers only when identical: plan it once.
      if (servers.has(server.name)) continue;
      servers.add(server.name);
      const config = serverConfig(server);
      if (typeof config === "string") {
        warnings.push(`MCP server "${server.name}" skipped for Codex: ${config}`);
        continue;
      }
      operations.push({
        kind: "merge-json",
        path: CONFIG,
        key: ["mcp_servers", server.name],
        value: config,
        approval: approvalId("mcp", server.layer, server.name),
      });
      if (server.layer !== ".") {
        warnings.push(
          `MCP server "${server.name}" from ${server.layer} is active for the whole project`,
        );
      }
    }
    for (const hook of content.hooks) {
      hooks++;
      operations.push({
        kind: "merge-json-item",
        path: CONFIG,
        key: ["hooks", EVENTS[hook.event]],
        id: `${hook.layer}:${hook.name}`,
        // Codex runs hooks in the session folder and has no project-dir variable.
        value: hookEntry("codex", ".", EDIT_TOOLS, hook),
        approval: approvalId("hook", hook.layer, hook.name),
      });
    }
    for (const plugin of content.plugins) {
      if (plugin.agent !== "codex") continue;
      operations.push(
        ...pluginOps(plugin, approvalId("plugin", plugin.layer, plugin.name), warnings),
      );
    }
  }

  if (ctx.autoSync) {
    operations.push(...autosyncFiles("codex", ctx.root, ctx.autoSync.cli), {
      kind: "merge-json-item",
      path: CONFIG,
      key: ["hooks", "SessionStart"],
      id: AUTOSYNC_ID,
      value: autosyncEntry("codex", "."),
    });
  }
  if (hooks > 0) {
    operations.push({
      kind: "write",
      path: hookRunnerPath("codex"),
      content: HOOK_RUNNER,
      readonly: true,
    });
  }
  if (hooks > 0 || ctx.autoSync) {
    warnings.push("Codex runs a new or changed hook only after you review it with /hooks");
    if (isLinkedWorktree(ctx.root)) {
      warnings.push(
        "This is a linked git worktree: Codex reads project hooks from the main checkout, so these hooks may not run here",
      );
    }
  }
  if (operations.some((op) => op.path === CONFIG) && !isTrusted(user, ctx.root)) {
    warnings.push(
      `Codex reads ${CONFIG} only in trusted projects: trust this folder when Codex asks`,
    );
  }

  return {
    agent: "codex" as const,
    scopes: ctx.scopes,
    operations,
    approvals: usedApprovals(ctx.approvals, operations),
    warnings,
  };
}

export const codex: Adapter = { id: "codex", name: "Codex", plan };
